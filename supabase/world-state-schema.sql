create or replace function public.link_game_event_records()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  state_change jsonb;
  target_type text;
  target_id bigint;
begin
  if new.location_id is null and new.location is not null then
    select unique_locations.id
    into new.location_id
    from (
      select min(id) as id
      from public.playable_locations
      where lower(trim(name)) = lower(trim(new.location))
      group by lower(trim(name))
      having count(*) = 1
    ) as unique_locations;
  end if;

  return new;
end
$$;

create or replace function public.create_game_event_links()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  state_change jsonb;
  target_type text;
  target_id bigint;
begin
  insert into public.event_characters (event_id, character_id, role)
  select new.id, affected.character_id, 'affected'
  from (
    select distinct unnest(new.affected_character_ids) as character_id
  ) as affected
  on conflict do nothing;

  insert into public.event_houses (event_id, house_id, role)
  select new.id, affected.house_id, 'affected'
  from (
    select distinct unnest(new.affected_house_ids) as house_id
  ) as affected
  on conflict do nothing;

  if new.location_id is not null then
    insert into public.event_locations (event_id, location_id, role)
    values (new.id, new.location_id, 'occurred_at')
    on conflict do nothing;
  end if;

  if exists (
    select 1
    from jsonb_object_keys(new.character_knowledge) as entry(character_id)
    where entry.character_id !~ '^[0-9]+$'
  ) then
    raise exception 'character_knowledge keys must be playable character IDs';
  end if;

  insert into public.event_characters (event_id, character_id, role, knowledge)
  select new.id, knowledge.character_id_text::integer, 'knows', knowledge.summary
  from jsonb_each_text(new.character_knowledge) as knowledge(character_id_text, summary)
  on conflict (event_id, character_id, role)
  do update set knowledge = excluded.knowledge;

  for state_change in
    select value from jsonb_array_elements(new.state_changes)
  loop
    target_type := state_change #>> '{target,type}';
    target_id := (state_change #>> '{target,id}')::bigint;

    insert into public.event_state_changes (
      event_id,
      change_type,
      description,
      character_id,
      house_id,
      location_id,
      war_id,
      diplomacy_record_id,
      structured_change
    )
    values (
      new.id,
      state_change ->> 'changeType',
      state_change ->> 'description',
      case when target_type = 'character' then target_id::integer end,
      case when target_type = 'house' then target_id end,
      case when target_type = 'location' then target_id end,
      case when target_type = 'war' then target_id end,
      case when target_type = 'diplomacy' then target_id end,
      coalesce(state_change -> 'structuredChange', '{}'::jsonb)
    );
  end loop;

  return new;
end
$$;

